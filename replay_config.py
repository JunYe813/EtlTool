"""
数据回放演示的配置 —— **写进代码，不走环境变量**

为什么不用环境变量 / Airflow Variable：

  · **环境变量**要经 systemd 的 `EnvironmentFile` 传到调度器进程。
    这条链路出过问题（"手动触发能跑、自动调度不跑"），而且很难查 ——
    因为 CLI 走 shell 环境、调度器走 EnvironmentFile，两条路径读到的不是一份配置，
    再加上 `airflow.cfg` 里还有一份首次生成的旧默认值，**三个来源互相覆盖**。

  · **Airflow Variable** 存在元数据库里，改起来方便，但读它要发 DB 查询。
    而 `schedule` / `end_date` 必须在 DAG **解析期**就确定，解析期查库是
    Airflow 官方不推荐的做法（每次解析一次查询，拖慢调度器）。

放在这个文件里的好处：

  · 改完 `git pull` 就生效 —— 调度器会自动重新解析 DAG，**不用重启服务**
  · 值和代码一起版本管理，改了什么一目了然
  · 没有"哪个来源生效"的歧义

⚠️ 演示结束后请把 SCHEDULE 和 REPLAY_UNIT_SECONDS 改回正式值（见下）。
"""

# ============================================================
# 运行模式
# ============================================================
#   "replay" —— 把真实时间映射到数据区间里的某一天（本项目默认）
#               源 CSV 是静态的（2016-09 ~ 2018-10），照真实日期跑会一直空转
#   "real"   —— 直接用真实日期（上游数据每天真实到达的场景）
RUN_MODE = "replay"

# ============================================================
# 回放参数（只在 RUN_MODE = "replay" 时生效）
# ============================================================

# 回放起点：真实时间从这一刻算「第 0 天」。
#   offset = floor((now - epoch) / 步长)；offset 为负会**钳到 0**，停在 2016-09-04 不动。
#
# ★ 演示前必须重新「对准表」—— 把它设成**你启动前的那一刻**：
#
#     cd /opt/etl_data && python3 - <<'PY'
#     import re, pathlib
#     from datetime import datetime, timezone
#     p = pathlib.Path("replay_config.py")
#     s = p.read_text(encoding="utf-8")
#     now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S")
#     new, n = re.subn(r'(?m)^REPLAY_EPOCH\s*=\s*"[^"]*"',
#                      f'REPLAY_EPOCH = "{now}"', s)
#     assert n == 1, f"没匹配到 REPLAY_EPOCH（匹配数={n}）"
#     p.write_text(new, encoding="utf-8")
#     print("REPLAY_EPOCH 已对准", now, "(UTC)")
#     PY
#
#   用命令而不是手敲，是为了避开时区/格式写错 —— 这个文件里踩过一次时间的坑。
#   ⚠️ 这一步会让 replay_config.py 在工作区变「脏」；演示结束后
#      `git checkout -- replay_config.py` 还原。
#
# 演示采用「从数据开头开始」（offset 0 = 2016-09-04）。注意源数据
# 2016-09 ~ 2016-10 **非常稀疏**：61 个日历天里只有 14 天有订单，
# 所以开头约 40 次运行大部分在处理**空天**。这是数据集本身的性质，
# 不是流水线的问题 —— 而且已实测验证：空天不会让任何一层失败。
#
# 支持两种写法：
#   '2026-09-15'            → 当天 00:00Z（粗粒度，白天启动会从区间中间开始）
#   '2026-09-15T06:36:00'   → 精确到秒（推荐，也是上面那条命令产出的格式）
REPLAY_EPOCH = "2026-09-15T06:36:00"

# 步长：真实时间每过这么多秒，数据时间推进一天。
# ⚠️ 必须和 SCHEDULE 的周期**配对**，否则回放不推进或跳着走：
#       调度每 2 分钟一次  → 120
#       调度每天 02:00     → 86400
#   跑 `python scripts/demo_replay.py preview` 可以一次验证两者是否匹配。
REPLAY_UNIT_SECONDS = 120


# ============================================================
# 调度周期
# ============================================================
# ⚠️ 演示配置：每 2 分钟一次，配合步长 120 → 每 2 分钟推进一天。
#    演示完请改回正式值：
#        SCHEDULE = "0 2 * * *"
#        REPLAY_UNIT_SECONDS = 86400
SCHEDULE = "0 0/2 * * * *"
